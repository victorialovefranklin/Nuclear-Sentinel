def read_csv_clean(path):
    df = pd.read_csv(path)
    df.columns = [str(c).strip() for c in df.columns]
    return df

def detect_time_col(df):
    for c in df.columns:
        lc = c.lower()
        if "time" in lc or "timestamp" in lc:
            return c
    return df.columns[0]

def parse_time_col(df):
    tcol = detect_time_col(df)
    ts = pd.to_datetime(df[tcol], errors="coerce")
    return tcol, ts

def attach_labels(test_df, label_df, source_name=""):
    """
    Corrected alignment strategy:
    1) Prefer row-wise alignment when row counts match.
    2) Else exact timestamp merge.
    3) Else nearest timestamp merge within 1 second.
    """
    test = test_df.copy()
    lab = label_df.copy()

    label_col = None
    for c in lab.columns:
        lc = c.lower()
        if lc in ("attack", "label", "class") or "attack" in lc or "label" in lc:
            label_col = c
            break
    if label_col is None:
        # choose last non-time column as fallback
        lt = detect_time_col(lab)
        non_time = [c for c in lab.columns if c != lt]
        if not non_time:
            raise ValueError(f"{source_name}: could not identify label column")
        label_col = non_time[-1]

    def normalize_labels(s):
        if pd.api.types.is_numeric_dtype(s):
            return pd.to_numeric(s, errors="coerce").fillna(0).astype(int).clip(0,1)
        z = s.astype(str).str.strip().str.lower()
        return z.str.contains("attack|anomaly|abnormal|1|true").astype(np.int8)

    if len(test) == len(lab):
        test["_label"] = normalize_labels(lab[label_col]).to_numpy()
        return test

    tt, test_ts = parse_time_col(test)
    lt, lab_ts = parse_time_col(lab)
    test["_timestamp_tmp"] = test_ts
    lab["_timestamp_tmp"] = lab_ts
    lab["_label_tmp"] = normalize_labels(lab[label_col])

    exact = test.merge(
        lab[["_timestamp_tmp", "_label_tmp"]],
        on="_timestamp_tmp",
        how="left"
    )
    fail = exact["_label_tmp"].isna().mean()
    if fail <= 0.01:
        exact["_label"] = exact["_label_tmp"].fillna(0).astype(np.int8)
        return exact.drop(columns=["_label_tmp"])

    # nearest merge within 1 sec
    left = test.sort_values("_timestamp_tmp")
    right = lab[["_timestamp_tmp","_label_tmp"]].sort_values("_timestamp_tmp")
    near = pd.merge_asof(
        left, right, on="_timestamp_tmp",
        direction="nearest", tolerance=pd.Timedelta(seconds=1)
    )
    fail = near["_label_tmp"].isna().mean()
    if fail > 0.01:
        raise ValueError(f"{source_name}: {fail:.2%} labels failed timestamp alignment.")
    near["_label"] = near["_label_tmp"].fillna(0).astype(np.int8)
    return near.drop(columns=["_label_tmp"]).sort_index()

