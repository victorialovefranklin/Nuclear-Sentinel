def find_one(candidates):
    matches = []
    for name in candidates:
        direct = BASE_DIR / name
        if direct.exists():
            matches.append(direct)
        matches.extend(BASE_DIR.rglob(name))
    # unique while preserving order
    uniq = []
    seen = set()
    for p in matches:
        s = str(p.resolve())
        if s not in seen:
            seen.add(s)
            uniq.append(p)
    if not uniq:
        return None
    if len(uniq) > 1:
        print(f"[WARNING] Multiple candidates for {candidates}; using {uniq[0]}")
    return uniq[0]

def required_file(candidates, label):
    p = find_one(candidates)
    if p is None:
        raise FileNotFoundError(f"Missing {label}. Tried: {candidates}")
    return p

