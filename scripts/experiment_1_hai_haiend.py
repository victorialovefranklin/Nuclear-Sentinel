def audited_hai_taxonomy(cols):
    """Return fixed publication-ready B1/B2 lists and a complete audit table."""
    actual = list(cols)
    actual_map = {str(c).upper(): c for c in actual}

    b1_expected = {c.upper(): c for c in HAI_B1_CONTROL_FEATURES}
    b2_expected = {c.upper(): c for c in HAI_B2_PHYSICAL_FEATURES}

    overlap = set(b1_expected).intersection(b2_expected)
    if overlap:
        raise RuntimeError(f"Audited HAI taxonomy contains B1/B2 overlap: {sorted(overlap)}")

    expected = set(b1_expected).union(b2_expected)
    actual_keys = set(actual_map)

    unexpected = sorted(actual_keys - expected)
    missing = sorted(expected - actual_keys)

    if unexpected or missing:
        msg = [
            "HAI 23.05 schema does not match the locked manually audited taxonomy.",
            f"Expected audited features: {len(expected)}",
            f"Observed numeric HAI features: {len(actual_keys)}",
        ]
        if unexpected:
            msg.append("Unexpected HAI features: " + ", ".join(actual_map[k] for k in unexpected))
        if missing:
            pretty_missing = [b1_expected.get(k, b2_expected.get(k, k)) for k in missing]
            msg.append("Missing audited HAI features: " + ", ".join(pretty_missing))
        msg.append(
            "Do not use a fallback classification. Verify the HAI 23.05 files/schema "
            "before publication."
        )
        raise RuntimeError("\n".join(msg))

    b1 = sorted(actual_map[k] for k in b1_expected)
    b2 = sorted(actual_map[k] for k in b2_expected)

    rows = []
    for c in b1:
        rows.append({
            "feature": c,
            "group": "B1_control_command",
            "classification": "manual_audit_fixed_v1",
            "audit_basis": HAI_TAXONOMY_NOTES.get(
                c,
                "HAI Technical Manual v4.0: command, setpoint, demand, actuator/controller "
                "state, or control-system state."
            ),
        })
    for c in b2:
        rows.append({
            "feature": c,
            "group": "B2_physical_process",
            "classification": "manual_audit_fixed_v1",
            "audit_basis": HAI_TAXONOMY_NOTES.get(
                c,
                "HAI Technical Manual v4.0: measured or derived physical-process quantity."
            ),
        })

    audit_df = pd.DataFrame(rows).sort_values(["group", "feature"]).reset_index(drop=True)

    if len(b1) != 58 or len(b2) != 28 or len(audit_df) != 86:
        raise RuntimeError(
            f"Locked taxonomy count check failed: B1={len(b1)}, B2={len(b2)}, "
            f"total={len(audit_df)}; expected 58/28/86."
        )

    return b1, b2, audit_df

