def prepare_numeric(df, features, medians=None):
    x = df.reindex(columns=features).apply(pd.to_numeric, errors="coerce")
    if medians is None:
        medians = x.median(numeric_only=True).reindex(features).fillna(0.0)
    x = x.fillna(medians).fillna(0.0).astype(np.float32)
    return x, medians

