def shap_outputs(model, test_df, features):
    try:
        import shap
    except Exception as e:
        print("[WARNING] SHAP unavailable:", e)
        return pd.DataFrame(), pd.DataFrame()

    x,_=prepare_numeric(test_df,features)
    sample=x.iloc[np.linspace(0,len(x)-1,min(2000,len(x)),dtype=int)]

    try:
        explainer=shap.TreeExplainer(model)
        sv=explainer.shap_values(sample)
        if isinstance(sv,list):
            arr=np.asarray(sv[-1])
        else:
            arr=np.asarray(sv)
            if arr.ndim==3:
                arr=arr[:,:, -1]
        imp=np.mean(np.abs(arr),axis=0)
        global_df=pd.DataFrame({"feature":features,"mean_abs_shap":imp}).sort_values("mean_abs_shap",ascending=False)
    except Exception as e:
        print("[WARNING] SHAP failed:", e)
        return pd.DataFrame(), pd.DataFrame()

    # representative attack row
    attack_idx=np.where(test_df["_label"].to_numpy(dtype=int)==1)[0]
    rep=pd.DataFrame()
    if len(attack_idx):
        ridx=int(attack_idx[len(attack_idx)//2])
        row=x.iloc[[ridx]]
        try:
            sv2=explainer.shap_values(row)
            if isinstance(sv2,list):
                arr2=np.asarray(sv2[-1])[0]
            else:
                arr2=np.asarray(sv2)
                if arr2.ndim==3:
                    arr2=arr2[:,:, -1]
                arr2=arr2[0]
            rep=pd.DataFrame({
                "feature":features,
                "feature_value":row.iloc[0].to_numpy(),
                "shap_value":arr2
            })
            rep["abs_shap"]=rep["shap_value"].abs()
            rep=rep.sort_values("abs_shap",ascending=False)
        except Exception as e:
            print("[WARNING] representative SHAP failed:", e)

    return global_df, rep

