def choose_dt_targets(df, physical, max_targets=12):
    cand = []
    for c in physical:
        s = pd.to_numeric(df[c], errors="coerce")
        if s.notna().sum() < 100:
            continue
        v = float(s.var(skipna=True))
        if np.isfinite(v) and v > 0:
            cand.append((c,v))
    cand.sort(key=lambda x: x[1], reverse=True)
    return [c for c,_ in cand[:max_targets]]

def add_dt_residuals(train_normal, frames, dt_inputs, dt_targets):
    out_frames = {k:v.copy() for k,v in frames.items()}
    if not dt_inputs or not dt_targets:
        return out_frames, []

    xtr, med = prepare_numeric(train_normal, dt_inputs)
    if len(xtr) > MAX_DT_FIT_ROWS:
        idx = np.linspace(0, len(xtr)-1, MAX_DT_FIT_ROWS, dtype=int)
        xtr_fit = xtr.iloc[idx]
        train_fit = train_normal.iloc[idx]
    else:
        xtr_fit = xtr
        train_fit = train_normal

    dt_cols = []
    for i, target in enumerate(dt_targets, start=1):
        y = pd.to_numeric(train_fit[target], errors="coerce")
        valid = y.notna().to_numpy()
        if valid.sum() < 100:
            continue

        model = RandomForestRegressor(
            n_estimators=DT_TREES,
            random_state=RANDOM_SEED+i,
            n_jobs=-1,
            max_features="sqrt",
            min_samples_leaf=2
        )
        model.fit(xtr_fit.loc[valid], y.loc[valid].astype(np.float32))

        scale = float(np.nanstd(y.to_numpy(dtype=float)))
        if not np.isfinite(scale) or scale <= 1e-12:
            scale = 1.0

        col = f"DTRES__{target}"
        dt_cols.append(col)

        for name, df in out_frames.items():
            x, _ = prepare_numeric(df, dt_inputs, med)
            pred = model.predict(x)
            actual = pd.to_numeric(df[target], errors="coerce").to_numpy(dtype=float)
            r = np.abs(actual - pred) / (scale + 1e-8)
            r[~np.isfinite(r)] = 0.0
            out_frames[name][col] = r.astype(np.float32)

        print(f"DT target {i}/{len(dt_targets)}: {target}")
    return out_frames, dt_cols

