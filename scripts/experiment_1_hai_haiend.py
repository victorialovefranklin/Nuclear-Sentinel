    pred_df=pd.DataFrame({"row_id":np.arange(len(test)),"true_label":test["_label"].to_numpy()})
    tcol=detect_time_col(test)
    if tcol in test.columns:
        pred_df["timestamp"]=test[tcol].astype(str).to_numpy()
    for alg in ["IsolationForest","RandomForest","GradientBoosting"]:
        for fs in ["B3","M1"]:
            pred_df[f"{alg}_{fs}_pred"]=preds[(alg,fs)]
