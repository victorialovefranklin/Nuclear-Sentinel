def paired_block_bootstrap(y, p_m1, p_b3):
    y=np.asarray(y).astype(int); a=np.asarray(p_m1).astype(int); b=np.asarray(p_b3).astype(int)
    n=len(y); rng=np.random.default_rng(RANDOM_SEED)
    starts=np.arange(0,n,BOOT_BLOCK_ROWS)
    blocks=[np.arange(s,min(s+BOOT_BLOCK_ROWS,n)) for s in starts]
    diffs=[]
    for _ in range(N_BOOT):
        chosen=rng.integers(0,len(blocks),size=len(blocks))
        idx=np.concatenate([blocks[j] for j in chosen])[:n]
        yy=y[idx]
        if len(np.unique(yy))<2:
            continue
        diffs.append(
            f1_score(yy,a[idx],average="macro",zero_division=0) -
            f1_score(yy,b[idx],average="macro",zero_division=0)
        )
    if not diffs:
        return np.nan,np.nan,np.nan
    d=np.asarray(diffs)
    return float(d.mean()), float(np.quantile(d,.025)), float(np.quantile(d,.975))

