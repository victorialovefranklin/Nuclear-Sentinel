def metrics(y, p, score=None):
    y = np.asarray(y).astype(int)
    p = np.asarray(p).astype(int)
    tn, fp, fn, tp = confusion_matrix(y,p,labels=[0,1]).ravel()
    fpr = fp/(fp+tn) if (fp+tn) else np.nan
    ap = average_precision_score(y, score) if score is not None and len(np.unique(y))>1 else np.nan
    return dict(
        macro_f1=f1_score(y,p,average="macro",zero_division=0),
        precision_attack=precision_score(y,p,pos_label=1,zero_division=0),
        recall_attack=recall_score(y,p,pos_label=1,zero_division=0),
        f1_attack=f1_score(y,p,pos_label=1,zero_division=0),
        fpr=fpr, average_precision=ap,
        tn=int(tn), fp=int(fp), fn=int(fn), tp=int(tp)
    )

def detection_latency_seconds(df, pred):
    y = df["_label"].to_numpy(dtype=int)
    pred = np.asarray(pred).astype(int)
    tcol, ts = parse_time_col(df)
    ts = ts.reset_index(drop=True)
    idx = np.where(y==1)[0]
    if len(idx)==0:
        return np.nan
    breaks = np.where(np.diff(idx)>1)[0]
    starts = np.r_[idx[0], idx[breaks+1]]
    ends = np.r_[idx[breaks], idx[-1]]
    vals = []
    for s,e in zip(starts,ends):
        hit = np.where(pred[s:e+1]==1)[0]
        if len(hit):
            j = s + int(hit[0])
            if pd.notna(ts.iloc[s]) and pd.notna(ts.iloc[j]):
                vals.append((ts.iloc[j]-ts.iloc[s]).total_seconds())
    return float(np.median(vals)) if vals else np.nan

