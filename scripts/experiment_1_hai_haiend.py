def fit_iso(train_normal, features):
    x, med = prepare_numeric(train_normal, features)
    m = IsolationForest(
        n_estimators=ISO_TREES,
        random_state=RANDOM_SEED,
        n_jobs=-1,
        contamination="auto",
        max_samples="auto"
    )
    m.fit(x)
    return m, med

def iso_score(m, df, features, med):
    x,_ = prepare_numeric(df, features, med)
    return -m.score_samples(x)

def fit_supervised(kind, train_df, features):
    x, med = prepare_numeric(train_df, features)
    y = train_df["_label"].to_numpy(dtype=int)
    if kind == "RandomForest":
        m = RandomForestClassifier(
            n_estimators=250,
            random_state=RANDOM_SEED,
            n_jobs=-1,
            class_weight="balanced_subsample"
        )
    else:
        m = HistGradientBoostingClassifier(
            random_state=RANDOM_SEED,
            max_iter=200,
            learning_rate=0.08,
            max_depth=None
        )
    m.fit(x,y)
    return m,med

def supervised_score(m, df, features, med):
    x,_ = prepare_numeric(df, features, med)
    p = m.predict(x)
    if hasattr(m, "predict_proba"):
        s = m.predict_proba(x)[:,1]
    else:
        s = p.astype(float)
    return p,s

