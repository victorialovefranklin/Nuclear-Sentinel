    end_context=[c for c in train.columns if c.startswith("END__") and pd.api.types.is_numeric_dtype(train[c])]

    b3=sorted(set(b1+b2))

    # STRICT chronological normal split BEFORE DT fitting/calibration.
    # The DT sees only the fit portion, never the held-out calibration portion.
    cut=max(1,int(len(train)*0.8))
    fit_raw=train.iloc[:cut].copy().reset_index(drop=True)
    cal_raw=train.iloc[cut:].copy().reset_index(drop=True)

    # DT residuals: fit on normal-fit only; apply unchanged to calibration/dev/test.
    dt_targets=choose_dt_targets(fit_raw,b2,MAX_DT_TARGETS)
    dt_inputs=[c for c in b3 if c not in dt_targets]
