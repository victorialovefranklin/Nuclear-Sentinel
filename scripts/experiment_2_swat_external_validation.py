def run_swat_external_validation():
    normal_path = resolve_any(SWAT_NORMAL_CANDIDATES, "SWaT Normal_v1")
    attack_path = resolve_any(SWAT_ATTACK_CANDIDATES, "SWaT Attack_v0")
    attack_log_path = resolve_any(SWAT_ATTACK_LIST_CANDIDATES, "SWaT attack list")

    required = [normal_path, attack_path, attack_log_path]
    missing = []

    audit = pd.DataFrame(
        [
            {
                "file": p.name,
                "exists": p.exists(),
                "resolved_path": str(p),
                "size_mb": round(p.stat().st_size / 1024**2, 3) if p.exists() else np.nan,
            }
            for p in required
        ]
    )
    audit.to_csv(AUDIT_DIR / "M08_SWaT_File_Audit.csv", index=False)
    print("\nSWaT FILE AUDIT")
    print(audit.to_string(index=False))

    if missing:
        raise FileNotFoundError(
            "Missing required SWaT file(s):\n" + "\n".join(missing)
        )

    print("\n" + "=" * 88)
    print("NUCLEAR SENTINEL AI — SWaT A1 EXTERNAL VALIDATION ONLY")
    print("=" * 88)

    normal = read_swat_data(normal_path, "normal")
    attack = read_swat_data(attack_path, "attack")
    attack_log = load_attack_log(attack_log_path)

    # Normal_v1 is normal-operation data by design.
    normal["_label"] = 0

    # Feature groups.
    sample = pd.concat([normal.head(100), attack.head(100)], ignore_index=True)
    b1, b2 = swat_feature_groups(sample)
    b3 = sorted(set(b1 + b2))

    if len(b1) < 2 or len(b2) < 2:
        raise RuntimeError(
            f"SWaT feature taxonomy failed: B1={len(b1)}, B2={len(b2)}"
        )

    print(f"\nB1 control/actuator features: {len(b1)}")
    print(f"B2 physical sensor features: {len(b2)}")
    print(f"B3 combined features: {len(b3)}")

    feature_review = pd.DataFrame(
        [{"feature": c, "group": "B1_control_actuator"} for c in b1]
        + [{"feature": c, "group": "B2_physical_sensor"} for c in b2]
    )
    feature_review.to_csv(
        AUDIT_DIR / "M08_SWaT_Feature_Taxonomy.csv", index=False
    )

    # STRICT chronological 80/20 normal split BEFORE DT training.
    cut = max(1, int(len(normal) * 0.80))
    fit_raw = normal.iloc[:cut].copy().reset_index(drop=True)
    calib_raw = normal.iloc[cut:].copy().reset_index(drop=True)

    # DT residual design: train only on the normal-fit period.
    dt_targets = choose_dt_targets(fit_raw, b2, MAX_DT_TARGETS)
    dt_inputs = [c for c in b3 if c not in dt_targets]

    dt_train = fit_raw
    if len(dt_train) > MAX_DT_FIT_ROWS:
        idx = np.linspace(0, len(dt_train) - 1, MAX_DT_FIT_ROWS, dtype=int)
        dt_train = dt_train.iloc[idx].copy()

    combined = pd.concat([
        fit_raw.assign(_swat_split="fit"),
        calib_raw.assign(_swat_split="calibration"),
        attack.assign(_swat_split="attack"),
    ], ignore_index=True, sort=False)

    combined_dt, dt_cols = add_dt_residuals(dt_train, combined, dt_inputs, dt_targets)

    m1 = sorted(set(b3 + dt_cols))
    feature_sets = {"B1": b1, "B2": b2, "B3": b3, "M1": m1}

    with open(AUDIT_DIR / "M09_SWaT_B1_B2_B3_M1_Feature_Sets.json", "w", encoding="utf-8") as f:
        json.dump(feature_sets, f, indent=2)

    fit_normal = combined_dt[combined_dt["_swat_split"] == "fit"].copy()
    calib_normal = combined_dt[combined_dt["_swat_split"] == "calibration"].copy()
    attack_dt = combined_dt[combined_dt["_swat_split"] == "attack"].copy()

    print(
        f"\nNormal fit rows: {len(fit_normal):,}; "
        f"normal calibration rows: {len(calib_normal):,}; "
        f"attack-workbook rows: {len(attack_dt):,}"
    )

    # Main B1/B2/B3/M1 benchmark.
    results = []
    preds = {}
    scores = {}
    models = {}
    medians_store = {}
    calibration_scores = {}

    for fs, features in feature_sets.items():
        print(f"\nTraining SWaT {fs} Isolation Forest ({len(features)} features)...")
        model, med = fit_isolation(fit_normal, features)

        calibration_score = isolation_scores(model, calib_normal, features, med)
        models[fs] = model
        medians_store[fs] = med
        calibration_scores[fs] = calibration_score
        threshold = float(
            np.quantile(calibration_score, ISO_CALIBRATION_QUANTILE)
        )

        test_score = isolation_scores(
            model, attack_dt, features, med
        )
        test_pred = (test_score >= threshold).astype(np.int8)

        met = metric_dict(
            attack_dt["_label"].to_numpy(),
            test_pred,
            test_score,
        )
        met.update({
            "dataset": "SWaT_A1",
            "algorithm": "IsolationForest",
            "feature_set": fs,
            "n_features": len(features),
            "threshold": threshold,
            "median_detection_latency_s": detection_latency_seconds(
                attack_dt, test_pred
            ),
        })
        results.append(met)
        preds[fs] = test_pred
        scores[fs] = test_score

        print(
            f"{fs}: Macro-F1={met['macro_f1']:.4f}, "
            f"Attack Recall={met['recall_attack']:.4f}, "
            f"FPR={met['fpr']:.4f}, "
            f"AP={met['average_precision']:.4f}"
        )

    r07 = pd.DataFrame(results)
    r07_path = TABLE_DIR / "R07_SWaT_A1_B1_B2_B3_M1_External_Validation.csv"
    r07.to_csv(r07_path, index=False)

    # Per-attack scenario analysis with interval validation.
    scenario_rows = []
    interval_audit_rows = []

    for _, r in attack_log.iterrows():
        resolved = resolve_attack_interval(
            attack_dt["_timestamp"],
            attack_dt["_label"].to_numpy(dtype=int),
            r["start_raw"],
            r["end_raw"],
        )

        interval_audit_rows.append({
            "attack_id": int(r["attack_id"]),
            "start_raw": r["start_raw"],
            "end_raw": r["end_raw"],
            "resolved_start": resolved["start"],
            "resolved_end": resolved["end"],
            "resolution_method": resolved["method"],
            "interval_validated": bool(resolved["resolved"]),
            "n_rows": int(resolved["n_rows"]),
            "attack_label_rows": int(resolved["attack_label_rows"]),
            "attack_fraction": resolved.get("attack_fraction", np.nan),
            "duration_seconds": resolved.get("duration_seconds", np.nan),
        })

        if not resolved["resolved"]:
            continue

        mask = attack_interval_mask(
            attack_dt["_timestamp"],
            resolved["start"],
            resolved["end"],
        )

        if not mask.any():
            continue

        for fs in ("B3", "M1"):
            p = np.asarray(preds[fs])[mask]
            s = np.asarray(scores[fs])[mask]

            scenario_rows.append({
                "attack_id": int(r["attack_id"]),
                "feature_set": fs,
                "attack_point": r["attack_point"],
                "attack_action": r["attack_action"],
                "expected_impact": r["expected_impact"],
                "unexpected_outcome": r["unexpected_outcome"],
                "start_raw": r["start_raw"],
                "end_raw": r["end_raw"],
                "resolved_start": resolved["start"],
                "resolved_end": resolved["end"],
                "interval_resolution_method": resolved["method"],
                "interval_validated": True,
                "n_rows": int(mask.sum()),
                "duration_seconds": float(
                    (resolved["end"] - resolved["start"]).total_seconds()
                ),
                "dataset_attack_label_rows": int(
                    attack_dt.loc[mask, "_label"].sum()
                ),
                "detected_any": bool(p.any()),
                "attack_window_recall": float(p.mean()),
                "max_anomaly_score": float(np.max(s)),
                "mean_anomaly_score": float(np.mean(s)),
            })

    r08 = pd.DataFrame(scenario_rows)

    # Hard validation guardrails for scenario-level publication output.
    if not r08.empty:
        bad_duration = r08["duration_seconds"].lt(0) | r08["duration_seconds"].gt(24 * 3600)
        bad_year = ~r08["resolved_start"].dt.year.isin(
            attack_dt["_timestamp"].dropna().dt.year.unique()
        )
        bad_attack_overlap = r08["dataset_attack_label_rows"].le(0)
        if bad_duration.any() or bad_year.any() or bad_attack_overlap.any():
            raise RuntimeError(
                "R08 interval validation failed: at least one scenario has an "
                "invalid duration/year or no overlap with labeled SWaT attack rows. "
                "Inspect M11_SWaT_Attack_Interval_Validation_Audit.csv."
            )

    r08_path = TABLE_DIR / "R08_SWaT_A1_Per_Attack_Scenario_Results_VALIDATED.csv"
    r08.to_csv(r08_path, index=False)

    interval_audit = pd.DataFrame(interval_audit_rows)
    interval_audit_path = AUDIT_DIR / "M11_SWaT_Attack_Interval_Validation_Audit.csv"
    interval_audit.to_csv(interval_audit_path, index=False)

    unresolved = interval_audit[interval_audit["interval_validated"] == False].copy()
    unresolved.to_csv(
        AUDIT_DIR / "M12_SWaT_Unresolved_Attack_Log_Rows.csv",
        index=False,
    )

    print("\nATTACK INTERVAL VALIDATION")
    print(
        f"Validated: {int(interval_audit['interval_validated'].sum())}/{len(interval_audit)} "
        f"attack-list records"
    )
    if not unresolved.empty:
        print("Unresolved attack IDs:", unresolved["attack_id"].tolist())

    # Primary statistical comparison.
    mean_diff, ci_low, ci_high = paired_block_bootstrap_difference(
        attack_dt,
        preds["M1"],
        preds["B3"],
        n_boot=N_BOOT,
        block_rows=BOOT_BLOCK_ROWS,
    )

    r09 = pd.DataFrame([{
        "dataset": "SWaT_A1",
        "algorithm": "IsolationForest",
        "comparison": "M1 - B3",
        "metric": "macro_f1",
        "mean_difference": mean_diff,
        "ci95_low": ci_low,
        "ci95_high": ci_high,
        "supports_improvement": bool(
            np.isfinite(ci_low) and ci_low > 0
        ),
    }])

    r09_path = TABLE_DIR / "R09_SWaT_A1_M1_vs_B3_Statistical_Comparison.csv"
    r09.to_csv(r09_path, index=False)

    # Threshold sensitivity — descriptive only; primary threshold remains 0.995.
    sensitivity_rows = []
    y_ext = attack_dt["_label"].to_numpy(dtype=int)
    for fs in ["B3", "M1"]:
        for q in THRESHOLD_QUANTILES:
            thr = float(np.quantile(calibration_scores[fs], q))
            pred_q = (scores[fs] >= thr).astype(np.int8)
            met = metric_dict(y_ext, pred_q, scores[fs])
            sensitivity_rows.append({"feature_set":fs, "quantile":q, "threshold":thr,
                                     "macro_f1":met["macro_f1"], "precision_attack":met["precision_attack"],
                                     "recall_attack":met["recall_attack"], "fpr":met["fpr"],
                                     "average_precision":met["average_precision"]})
    r10 = pd.DataFrame(sensitivity_rows)
    r10_path = TABLE_DIR / "R10_SWaT_A1_Threshold_Sensitivity.csv"
    r10.to_csv(r10_path, index=False)

    # Distribution shift: calibration-normal vs normal rows inside the external attack workbook.
    ext_normal_mask = (attack_dt["_label"].to_numpy(dtype=int) == 0)
    shift_rows = []
    score_sets = {}
    for fs in ["B3", "M1"]:
        cal_sc = np.asarray(calibration_scores[fs], dtype=float)
        ext_sc = np.asarray(scores[fs], dtype=float)[ext_normal_mask]
        ks = ks_2samp(cal_sc, ext_sc, alternative="two-sided", mode="auto")
        w = float(wasserstein_distance(cal_sc, ext_sc))
        scale = float(np.std(cal_sc))
        nw = w / scale if np.isfinite(scale) and scale > 1e-12 else np.nan
        shift_rows.append({"feature_set":fs, "calibration_mean":float(np.mean(cal_sc)),
                           "external_normal_mean":float(np.mean(ext_sc)),
                           "mean_shift":float(np.mean(ext_sc)-np.mean(cal_sc)),
                           "ks_statistic":float(ks.statistic), "ks_p_value":float(ks.pvalue),
                           "wasserstein":w, "normalized_wasserstein":nw})
        score_sets[(fs,"calibration")] = cal_sc
        score_sets[(fs,"external_normal")] = ext_sc
    r11 = pd.DataFrame(shift_rows)
    r11_path = TABLE_DIR / "R11_SWaT_A1_Normal_Data_Distribution_Shift.csv"
    r11.to_csv(r11_path, index=False)

    # Data audit.
    pd.DataFrame([
        {
            "file": normal_path.name,
            "rows": len(normal),
            "columns": len(normal.columns),
            "attack_rows": int(normal["_label"].sum()),
        },
        {
            "file": attack_path.name,
            "rows": len(attack),
            "columns": len(attack.columns),
            "attack_rows": int(attack["_label"].sum()),
        },
        {
            "file": attack_log_path.name,
            "rows": len(attack_log),
            "columns": len(attack_log.columns),
            "attack_rows": np.nan,
        },
    ]).to_csv(
        AUDIT_DIR / "M10_SWaT_A1_Data_Audit.csv",
        index=False,
    )

    # Reduced publication figures: 5 total.
    fig01_external_validation_summary(r07, r09)
    fig02_discrimination_diagnostics(attack_dt["_label"].to_numpy(), scores, preds)
    fig03_threshold_sensitivity(r10)
    fig04_distribution_shift(score_sets, r11)
    residual_compare = fig05_dt_residual_behavior(fit_normal, attack_dt, dt_cols)
    residual_compare.to_csv(TABLE_DIR / "R12_SWaT_A1_DT_Residual_Normal_vs_Attack.csv", index=False)
    pd.DataFrame(FIGURE_MANIFEST).to_csv(AUDIT_DIR / "M13_Figure_Manifest.csv", index=False)

    # Environment audit.
    pd.DataFrame([{
        "python": sys.version.split()[0],
        "platform": platform.platform(),
        "pandas": pd.__version__,
        "numpy": np.__version__,
    }]).to_csv(
        AUDIT_DIR / "M00_SWaT_Environment_Versions.csv",
        index=False,
    )

    print("\n" + "=" * 88)
    print("SWaT EXTERNAL VALIDATION COMPLETE")
    print("=" * 88)

    print("\nR07 MAIN RESULTS")
    print(
        r07[
            [
                "feature_set",
                "macro_f1",
                "precision_attack",
                "recall_attack",
                "fpr",
                "average_precision",
                "median_detection_latency_s",
            ]
        ].to_string(index=False)
    )

    print("\nR09 PRIMARY M1 vs B3 COMPARISON")
    print(r09.to_string(index=False))

    print("\nSaved to:")
    print(OUT_DIR)
    print("\nKey files:")
    print(r07_path)
    print(r08_path)
    print(r09_path)
    print(r10_path)
    print(r11_path)
    print(interval_audit_path)
    print(f"\nNumbered publication figures: {len(FIGURE_MANIFEST)}")

    return r07, r08, r09, r10, r11


