def macro_f1_binary(y, p):
    return f1_score(y, p, average="macro", zero_division=0)


def paired_block_bootstrap_difference(
    df, pred_m1, pred_b3, n_boot=1000, block_rows=300
):
    y = df["_label"].to_numpy(dtype=int)
    a = np.asarray(pred_m1, dtype=int)
    b = np.asarray(pred_b3, dtype=int)
    n = len(y)

    if n < 2:
        return np.nan, np.nan, np.nan

    rng = np.random.default_rng(RANDOM_SEED)
    starts = np.arange(0, n, block_rows)
    blocks = [np.arange(s, min(s + block_rows, n)) for s in starts]

    diffs = []
    for _ in range(n_boot):
        chosen = rng.integers(0, len(blocks), size=len(blocks))
        idx = np.concatenate([blocks[j] for j in chosen])[:n]

        yy = y[idx]
        if len(np.unique(yy)) < 2:
            continue

        diffs.append(
            macro_f1_binary(yy, a[idx]) - macro_f1_binary(yy, b[idx])
        )

    if not diffs:
        return np.nan, np.nan, np.nan

    diffs = np.asarray(diffs)
    return (
        float(np.mean(diffs)),
        float(np.quantile(diffs, 0.025)),
        float(np.quantile(diffs, 0.975)),
    )


