def read_swat_data(path: Path, kind: str) -> pd.DataFrame:
    """Read SWaT CSV or XLSX while preserving the distributed A1 structure."""
    print(f"Reading {path.name} ...")
    if path.suffix.lower() == ".xlsx":
        # Normal workbook has process-stage row then header; attack workbook uses the same
        # distributed two-row structure in many copies. Try header=1 first, then validate.
        df = pd.read_excel(path, header=1, engine="openpyxl")
        if not any(str(c).strip().lower() == "timestamp" for c in df.columns):
            df = pd.read_excel(path, header=0, engine="openpyxl")
    else:
        # The user's Normal_v1 CSV retains the stage row; Attack_v0 CSV has its real header on row 1.
        header = 1 if kind == "normal" else 0
        df = pd.read_csv(path, header=header, low_memory=False, encoding="utf-8-sig")
        if not any(str(c).strip().lower() == "timestamp" for c in df.columns):
            # Safe fallback if a CSV was exported differently.
            df = pd.read_csv(path, header=0, low_memory=False, encoding="utf-8-sig")

    df.columns = [str(c).strip().replace(" ", "") for c in df.columns]
    tcol = next((c for c in df.columns if c.lower() == "timestamp"), None)
    lcol = next((c for c in df.columns if c.lower().replace("/", "") == "normalattack"), None)
    if tcol is None:
        raise ValueError(f"Timestamp column not found in {path.name}")

    raw_time = df[tcol].astype(str).str.strip()
    ts = pd.to_datetime(raw_time, dayfirst=True, errors="coerce")
    if ts.isna().mean() > 0.05:
        ts = ts.fillna(pd.to_datetime(raw_time, errors="coerce"))
    df["_timestamp"] = ts

    if lcol is not None:
        labels = df[lcol].astype(str).str.strip().str.lower()
        df["_label"] = labels.str.contains("attack").astype(np.int8)
    else:
        df["_label"] = 0

    bad_ts = int(df["_timestamp"].isna().sum())
    if bad_ts:
        print(f"[WARNING] {path.name}: {bad_ts:,} rows have unparsed timestamps.")
    print(f"Loaded {len(df):,} rows × {len(df.columns):,} columns; attack rows={int(df['_label'].sum()):,}")
    return df


def load_attack_log(path: Path) -> pd.DataFrame:
    """
    Load the SWaT attack log without silently correcting dates.

    Important:
    - Some rows have time-only End Time values.
    - Some rows have missing End Time values.
    - Rows 37-41 in some distributed copies contain 2015-01-02 dates even
      though the attack dataset itself extends into January 2016.
    Those cases are resolved later against the actual attack-data timestamps.
    """
    print(f"Reading {path.name} ...")
    if path.suffix.lower() == ".xlsx":
        log = pd.read_excel(path, engine="openpyxl")
    else:
        log = pd.read_csv(path, low_memory=False, encoding="utf-8-sig")
    log.columns = [str(c).strip() for c in log.columns]

    def first_present(row, names):
        for name in names:
            if name in row.index and not pd.isna(row[name]):
                return row[name]
        return np.nan

    rows = []
    for _, r in log.iterrows():
        attack_no = first_present(r, ["Attack #", "Attack#", "Attack No", "Attack No."])
        start_val = first_present(r, ["Start Time", "Start"])
        end_val = first_present(r, ["End Time", "End"])

        if pd.isna(attack_no) or pd.isna(start_val):
            continue

        start_ts = pd.to_datetime(start_val, errors="coerce", dayfirst=True)
        if pd.isna(start_ts):
            continue

        end_ts = pd.NaT
        if not pd.isna(end_val):
            # Excel can store End Time as time-only.
            if isinstance(end_val, pd.Timestamp):
                end_ts = end_val
            elif hasattr(end_val, "hour") and not isinstance(end_val, str):
                try:
                    end_ts = pd.Timestamp.combine(start_ts.date(), end_val)
                    if end_ts < start_ts:
                        end_ts += pd.Timedelta(days=1)
                except Exception:
                    pass

            if pd.isna(end_ts):
                parsed = pd.to_datetime(end_val, errors="coerce", dayfirst=True)
                if pd.notna(parsed):
                    if parsed.year == 1900:
                        end_ts = pd.Timestamp.combine(start_ts.date(), parsed.time())
                        if end_ts < start_ts:
                            end_ts += pd.Timedelta(days=1)
                    else:
                        end_ts = parsed

        rows.append({
            "attack_id": int(float(attack_no)),
            "start_raw": start_ts,
            "end_raw": end_ts,
            "attack_point": first_present(r, ["Attack Point", "Attack Points"]),
            "attack_action": first_present(
                r,
                ["Attack Actual Change", "Attack", "Actual Change", "Attack Action"]
            ),
            "expected_impact": first_present(
                r,
                ["Expected Impact or attacker intent", "Expected Impact", "Attacker Intent"]
            ),
            "unexpected_outcome": first_present(
                r,
                ["Unexpected Outcome", "Observed Outcome"]
            ),
        })

    out = pd.DataFrame(rows)
    print(
        f"Attack log: {len(out):,} records; "
        f"{int(out['end_raw'].notna().sum()) if not out.empty else 0:,} have explicit end times."
    )
    return out


