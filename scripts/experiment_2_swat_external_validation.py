def choose_dt_targets(df: pd.DataFrame, physical_features, max_targets=12):
    candidates = []
    for c in physical_features:
        if c not in df.columns:
            continue
        s = pd.to_numeric(df[c], errors="coerce")
        if s.notna().sum() < 100:
            continue
        variance = float(s.var(skipna=True))
        if np.isfinite(variance) and variance > 0:
            candidates.append((c, variance))

    candidates.sort(key=lambda x: x[1], reverse=True)
    return [c for c, _ in candidates[:max_targets]]


def prepare_numeric(df: pd.DataFrame, features, medians=None):
    x = df.reindex(columns=features).apply(pd.to_numeric, errors="coerce")

    if medians is None:
        medians = x.median(numeric_only=True)
        medians = medians.reindex(features).fillna(0.0)

    x = x.fillna(medians).fillna(0.0)
    return x.astype(np.float32), medians


def add_dt_residuals(train_normal, combined, dt_inputs, dt_targets):
    out = combined.copy()
    dt_cols = []

    if not dt_targets or not dt_inputs:
        return out, dt_cols

    x_train, input_medians = prepare_numeric(train_normal, dt_inputs)
    x_all, _ = prepare_numeric(combined, dt_inputs, input_medians)

    print(
        f"Building DT residuals for {len(dt_targets)} physical targets "
        f"using {len(dt_inputs)} input variables..."
    )

    for i, target in enumerate(dt_targets, start=1):
        y_train = pd.to_numeric(train_normal[target], errors="coerce")
        valid = y_train.notna().to_numpy()

        if valid.sum() < 100:
            continue

        model = RandomForestRegressor(
            n_estimators=DT_TREES,
            random_state=RANDOM_SEED + i,
            n_jobs=-1,
            max_features="sqrt",
            min_samples_leaf=2,
        )
        model.fit(x_train.loc[valid], y_train.loc[valid].astype(np.float32))

        pred = model.predict(x_all)
        actual = pd.to_numeric(out[target], errors="coerce").to_numpy(dtype=float)

        scale = float(np.nanstd(y_train.to_numpy(dtype=float)))
        if not np.isfinite(scale) or scale <= 1e-12:
            scale = 1.0

        col = f"DTRES__{target}"
        residual = np.abs(actual - pred) / (scale + 1e-8)
        residual[~np.isfinite(residual)] = 0.0
        out[col] = residual.astype(np.float32)
        dt_cols.append(col)

        print(f"  DT target {i}/{len(dt_targets)}: {target}")

    return out, dt_cols


