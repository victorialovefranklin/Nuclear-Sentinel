def swat_feature_groups(df: pd.DataFrame):
    meta = {"_timestamp", "_label", "Timestamp", "Normal/Attack", "NormalAttack"}

    numeric = [
        c for c in df.columns
        if c not in meta and pd.api.types.is_numeric_dtype(df[c])
    ]

    # Control/actuator state variables.
    control = [
        c for c in numeric
        if c.upper().startswith(("MV", "P", "UV"))
        and not c.upper().startswith("PIT")
    ]

    # Physical-process sensor variables.
    physical = [
        c for c in numeric
        if c.upper().startswith(("FIT", "LIT", "AIT", "DPIT", "PIT"))
    ]

    return sorted(set(control)), sorted(set(physical))


