def _combine_date_and_time(date_source, time_source):
    """Combine the date from one timestamp with the clock time from another."""
    return pd.Timestamp.combine(
        pd.Timestamp(date_source).date(),
        pd.Timestamp(time_source).time(),
    )


def _candidate_interval_years(start, end, dataset_years):
    """
    Generate conservative date candidates for an explicit attack interval.

    Important:
    - Never carry an unrelated calendar date/year from a time-only End Time.
    - For every candidate, the end clock time is anchored to the candidate
      start date; if it is earlier than the start clock time, it rolls to
      the next day.
    """
    candidates = []

    if pd.isna(start) or pd.isna(end):
        return candidates

    def build_interval(candidate_start):
        candidate_start = pd.Timestamp(candidate_start)
        candidate_end = _combine_date_and_time(candidate_start, end)
        if candidate_end < candidate_start:
            candidate_end += pd.Timedelta(days=1)
        return candidate_start, candidate_end

    # Exact start date, but end is deliberately rebuilt from its TIME only.
    try:
        s, e = build_interval(start)
        candidates.append(("attack_log_start_date_end_time", s, e))
    except Exception:
        pass

    # Same month/day/time mapped only to years that actually occur in SWaT.
    for yr in sorted(set(int(y) for y in dataset_years)):
        try:
            s = pd.Timestamp(start).replace(year=yr)
            s, e = build_interval(s)
            candidates.append((f"year_aligned_{yr}", s, e))
        except Exception:
            pass

    uniq = []
    seen = set()
    for source, s, e in candidates:
        key = (s, e)
        if key not in seen:
            seen.add(key)
            uniq.append((source, s, e))
    return uniq


def _contiguous_attack_episode(timestamps, labels, anchor, tolerance_seconds=120):
    """
    Resolve an attack episode only when the SWaT dataset itself contains a
    labeled attack at or very near the supplied start time.
    """
    if pd.isna(anchor):
        return None

    ts = pd.Series(timestamps).reset_index(drop=True)
    y = np.asarray(labels, dtype=int)

    valid = ts.notna()
    if not valid.any():
        return None

    deltas = (ts - anchor).abs().dt.total_seconds()
    if deltas.isna().all():
        return None

    nearest = int(deltas.idxmin())
    if float(deltas.iloc[nearest]) > tolerance_seconds:
        return None

    if y[nearest] != 1:
        local = np.where((deltas.to_numpy() <= tolerance_seconds) & (y == 1))[0]
        if len(local) == 0:
            return None
        nearest = int(local[np.argmin(deltas.iloc[local].to_numpy())])

    left = nearest
    right = nearest
    while left > 0 and y[left - 1] == 1:
        left -= 1
    while right < len(y) - 1 and y[right + 1] == 1:
        right += 1

    return ts.iloc[left], ts.iloc[right]


def resolve_attack_interval(timestamps, labels, start_raw, end_raw):
    """
    Validate a SWaT attack-list interval against actual dataset timestamps.

    Explicit-end records:
      1. Rebuild the end timestamp from the END CLOCK TIME anchored to the
         candidate start date.
      2. Consider only years present in the SWaT dataset.
      3. Require overlap with labeled attack rows.
      4. Reject implausibly long intervals.

    Missing-end records:
      Resolve only from a contiguous labeled attack episode near the start.

    This prevents time-only Excel End Time values from introducing an
    unrelated current/1900/2026 date into R08.
    """
    ts = pd.Series(timestamps).reset_index(drop=True)
    y = np.asarray(labels, dtype=int)
    valid_ts = ts.dropna()

    unresolved = {
        "resolved": False,
        "start": pd.NaT,
        "end": pd.NaT,
        "method": "unresolved",
        "n_rows": 0,
        "attack_label_rows": 0,
    }

    if valid_ts.empty or pd.isna(start_raw):
        unresolved["method"] = "unresolved_no_timestamp"
        return unresolved

    dataset_years = valid_ts.dt.year.unique().tolist()

    if pd.notna(end_raw):
        best = None
        for method, s, e in _candidate_interval_years(
            start_raw, end_raw, dataset_years
        ):
            duration_s = (e - s).total_seconds()

            # SWaT attacks are short episodes. This is a guardrail against
            # accidental cross-date/cross-year intervals, not an inferred end.
            if duration_s < 0 or duration_s > 24 * 3600:
                continue

            mask = ts.between(s, e, inclusive="both").to_numpy()
            n_rows = int(mask.sum())
            attack_rows = int(y[mask].sum()) if n_rows else 0

            # A scenario called "validated" must overlap actual labeled attack
            # data. Merely overlapping timestamps is not enough.
            if n_rows == 0 or attack_rows == 0:
                continue

            attack_fraction = attack_rows / n_rows
            score = (attack_fraction, attack_rows, -n_rows)

            if best is None or score > best["score"]:
                best = {
                    "resolved": True,
                    "start": s,
                    "end": e,
                    "method": method,
                    "n_rows": n_rows,
                    "attack_label_rows": attack_rows,
                    "attack_fraction": attack_fraction,
                    "duration_seconds": duration_s,
                    "score": score,
                }

        if best is not None:
            best.pop("score", None)
            return best

        unresolved["method"] = "unresolved_explicit_interval_no_attack_overlap"
        return unresolved

    # Missing End Time: do not invent one from the attack log.
    start_candidates = [("start_exact", pd.Timestamp(start_raw))]
    for yr in sorted(set(int(y_) for y_ in dataset_years)):
        try:
            start_candidates.append(
                (f"start_year_aligned_{yr}", pd.Timestamp(start_raw).replace(year=yr))
            )
        except Exception:
            pass

    seen = set()
    for method, anchor in start_candidates:
        if anchor in seen:
            continue
        seen.add(anchor)

        episode = _contiguous_attack_episode(
            ts, y, anchor, tolerance_seconds=120
        )
        if episode is not None:
            s, e = episode
            mask = ts.between(s, e, inclusive="both").to_numpy()
            n_rows = int(mask.sum())
            attack_rows = int(y[mask].sum())
            return {
                "resolved": True,
                "start": s,
                "end": e,
                "method": f"{method}_derived_from_dataset_attack_labels",
                "n_rows": n_rows,
                "attack_label_rows": attack_rows,
                "attack_fraction": attack_rows / n_rows if n_rows else np.nan,
                "duration_seconds": (e - s).total_seconds(),
            }

    unresolved["method"] = "unresolved_missing_end_no_labeled_episode"
    return unresolved


def attack_interval_mask(timestamps, start, end):
    """Return mask for an already-resolved interval."""
    if pd.isna(start) or pd.isna(end):
        return np.zeros(len(timestamps), dtype=bool)
    return pd.Series(timestamps).between(start, end, inclusive="both").to_numpy()


