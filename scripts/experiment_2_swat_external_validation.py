def fit_isolation(train_df, features):
    x, med = prepare_numeric(train_df, features)
    model = IsolationForest(
        n_estimators=ISO_TREES,
        random_state=RANDOM_SEED,
        n_jobs=-1,
        contamination="auto",
        max_samples="auto",
    )
    model.fit(x)
    return model, med


def isolation_scores(model, df, features, medians):
    x, _ = prepare_numeric(df, features, medians)
    # Larger = more anomalous.
    return -model.score_samples(x)


def metric_dict(y_true, y_pred, scores):
    y_true = np.asarray(y_true).astype(int)
    y_pred = np.asarray(y_pred).astype(int)
    scores = np.asarray(scores, dtype=float)

    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()
    fpr = fp / (fp + tn) if (fp + tn) else np.nan

    return {
        "macro_f1": f1_score(y_true, y_pred, average="macro", zero_division=0),
        "precision_attack": precision_score(y_true, y_pred, pos_label=1, zero_division=0),
        "recall_attack": recall_score(y_true, y_pred, pos_label=1, zero_division=0),
        "f1_attack": f1_score(y_true, y_pred, pos_label=1, zero_division=0),
        "fpr": fpr,
        "average_precision": (
            average_precision_score(y_true, scores)
            if len(np.unique(y_true)) > 1 else np.nan
        ),
        "tn": int(tn),
        "fp": int(fp),
        "fn": int(fn),
        "tp": int(tp),
    }


def detection_latency_seconds(df, pred):
    """
    Median latency across contiguous labeled attack episodes present in the
    SWaT attack workbook itself.
    """
    y = df["_label"].to_numpy(dtype=int)
    pred = np.asarray(pred, dtype=int)
    ts = df["_timestamp"].reset_index(drop=True)

    attack_idx = np.where(y == 1)[0]
    if len(attack_idx) == 0:
        return np.nan

    # Find contiguous labeled attack runs.
    breaks = np.where(np.diff(attack_idx) > 1)[0]
    starts = np.r_[attack_idx[0], attack_idx[breaks + 1]]
    ends = np.r_[attack_idx[breaks], attack_idx[-1]]

    latencies = []
    for s, e in zip(starts, ends):
        hits = np.where(pred[s:e+1] == 1)[0]
        if len(hits) == 0:
            continue
        first = s + int(hits[0])
        if pd.notna(ts.iloc[s]) and pd.notna(ts.iloc[first]):
            latencies.append((ts.iloc[first] - ts.iloc[s]).total_seconds())

    return float(np.median(latencies)) if latencies else np.nan


